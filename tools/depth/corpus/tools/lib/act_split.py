def marginal_heads(text: str, declaration: dict) -> list:
    """Заголовки-заметки на полях по таблице из `articles.json`.

    Единица деления глав XIV–XV «Левиафана» — маргиналия издания 1651 года, у
    которой номера в тексте нет вовсе. Таблица живёт в декларации акта по той
    же причине, что и у `word` с `ordinal`: список заголовков суть факт об
    ЭТОМ документе. Ровно ту же таблицу читает конвенция `marginal` в
    verify/ci/gates/sources/check_source_pinning.py; две копии соглашения разошлись бы, как однажды
    разошлись `ARTICLE_RE` и срез статьи."""
    table = (declaration or {}).get("headings") or {}
    by_phrase = {str(phrase): str(number) for number, phrase in table.items()}
    if not by_phrase:
        return []
    alternatives = "|".join(re.escape(p) for p in
                            sorted(by_phrase, key=lambda p: (-len(p), p)))
    pattern = re.compile(rf"^({alternatives})$", re.MULTILINE)
    return [_Head(by_phrase[m.group(1)], m.group(1))
            for m in pattern.finditer(text)]


