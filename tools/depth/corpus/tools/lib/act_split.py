    # конвенции кодекс был бы для обеих мер §33.1 НЕВИДИМ МОЛЧА — тот же
    # отказ, что уже случался с «26-бап», с топиком Fannie Mae и с римской
    # статьёй договора.
    #
    # В автоопределение НЕ входит: слово «Rule» с номером стоит в любом
    # регламенте, цитирующем свои же правила, и первый такой документ получил
    # бы чужую единицу деления молча. Включается только объявлением
