class _Head(NamedTuple):
    """Заголовок единицы в виде, который ждёт `depth`: номер и название.

    Нужен там, где номер единицы В ТЕКСТЕ НЕ СТОИТ и регулярным выражением
    получен быть не может. «Қара сөз» называет слова числительными прописью
    («ЖИЫРМА ЖЕТІНШІ СӨЗ»), а locator фрагмента — числом (`article/27`), и
    без приведения одного к другому мера не свела бы ни одного якоря: все
    сорок пять слов вышли бы SOURCE_ONLY при полностью выведенном пакете.
    """

    number: str
    title: str

    def group(self, index: int) -> str:
        return self.number if index == 1 else self.title


def word_heads(text: str, declaration: dict) -> list:
    """Заголовки слов по таблице числительных из `articles.json`.

    Таблица живёт в декларации акта, а не здесь, — по той же причине, по
    которой там же объявлена сама единица: числительные суть факт об этом
    произведении. Ровно ту же таблицу читает `verify/ci/gates/sources/check_source_pinning.py`;
    две копии соглашения разошлись бы, как однажды разошлись `ARTICLE_RE` и
    срез статьи."""
    ordinals = (declaration or {}).get("ordinals") or {}
    by_phrase = {str(phrase): str(number) for number, phrase in ordinals.items()}
    if not by_phrase:
        return []
    alternatives = "|".join(re.escape(p) for p in
                            sorted(by_phrase, key=lambda p: (-len(p), p)))
    pattern = re.compile(rf"^({alternatives}) СӨЗ$", re.MULTILINE)
    return [_Head(by_phrase[m.group(1)], f"{m.group(1)} СӨЗ")
            for m in pattern.finditer(text)]


def ordinal_heads(text: str, declaration: dict) -> list:
    """Заголовки пунктов, названных порядковым числительным.

    Атлантическая хартия делится на «First,» … «Eighth,»: номера в тексте нет
    вовсе, как и у слов «Қара сөз», — есть числительное. Таблица приведения
    живёт в декларации акта по той же причине, по которой там же объявлена
    единица: список числительных суть факт об ЭТОМ документе. Ровно ту же
    таблицу читает конвенция `ordinal` в verify/ci/gates/sources/check_source_pinning.py; две копии
    соглашения разошлись бы, как однажды разошлись `ARTICLE_RE` и срез
    статьи."""
    ordinals = (declaration or {}).get("ordinals") or {}
    by_phrase = {str(phrase): str(number) for number, phrase in ordinals.items()}
    if not by_phrase:
        return []
    alternatives = "|".join(re.escape(p) for p in
                            sorted(by_phrase, key=lambda p: (-len(p), p)))
    pattern = re.compile(rf"^({alternatives}), (.{{0,90}})", re.MULTILINE)
    return [_Head(by_phrase[m.group(1)], m.group(2).strip())
            for m in pattern.finditer(text)]


