#: Правило Йорк-Антверпенских правил. Выражение обязано совпадать со `scan`
#: конвенции `yar_rule` в verify/ci/gates/sources/check_source_pinning.py — две меры §33.1 говорят
#: об одном множестве единиц. Регистр разный у разных редакций ОДНОГО акта
#: (2004 — прописными, 2016 — строчными), поэтому выражение регистронезависимо.
YAR_RULE_RE = re.compile(
    r"^Rule (of Interpretation|Paramount|[A-G]|[IVX]+)(?=[ .,–—-]|$)[ .,–—-]*(.{0,90})",
    re.MULTILINE | re.IGNORECASE)


def yar_rule_heads(text: str) -> list:
    """Заголовки правил ЙАП, приведённые к номеру учёта.

    Отдельная функция, а не строка в `DECLARED_CONVENTIONS`, по той же
    причине, что у `policy_section`: номер в тексте есть, но нуждается в
    приведении. Именованные правила («Rule of Interpretation») дают номер
    одним словом — locator не терпит пробела внутри сегмента пути; буквенные
    и римские приводятся к прописным, потому что редакции набирают их
    по-разному, а `impact-editions` сравнил бы `rule/PARAMOUNT` и
    `rule/Paramount` как разные единицы.
    """
    return [_Head(_yar_rule_number(m.group(1)), m.group(2).strip())
            for m in YAR_RULE_RE.finditer(text)]


def _yar_rule_number(raw: str) -> str:
    if raw.lower().startswith("of "):
        return "Interpretation"
    if raw.lower() == "paramount":
        return "Paramount"
    return raw.upper()


