#: Приведение «таблица.пункт» к номеру учёта и обратно. Ровно та же таблица
#: живёт в конвенции `tabula_item` verify/ci/gates/sources/check_source_pinning.py; две копии
#: соглашения разошлись бы, как однажды разошлись `ARTICLE_RE` и срез статьи.
_TABULA_NUMBER = {r: str(n) for n, r in enumerate(
    ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII"], 1)}
_TABULA_NUMBER["Fr"] = "0"

TABULA_ITEM_RE = re.compile(r"^((?:[IVX]+|Fr)\.\d+)\.\s(.{0,90})", re.MULTILINE)


def tabula_item_heads(text: str) -> list:
    """Заголовки «VIII.2.» / «Fr.1.», приведённые к номеру учёта `8-2` / `0-1`.

    Причина приведения та же, что у `roman_article_heads`: номер в тексте есть,
    но записан римской цифрой таблицы, а локаторы фрагментов числовые
    (`article/8-2`) — без приведения мера не свела бы ни одного якоря, и весь
    реконструированный свод вышел бы SOURCE_ONLY при живом пакете.

    `Fr` → таблица `0` («таблица неизвестна»): fragmenta incertae sedis суть
    пункты, которым ИЗДАТЕЛЬ отказался назначить таблицу, и приписать им XIII
    значило бы сделать за него этот выбор. Ноль в закреплённых байтах не
    встречается ни разу."""
    out = []
    for match in TABULA_ITEM_RE.finditer(text):
        prefix, item = match.group(1).split(".")
        out.append(_Head(f"{_TABULA_NUMBER[prefix]}-{item}", match.group(0).strip()))
    return out


#: Единицы, чьи заголовки собираются вспомогательной функцией и позиции в
#: документе не несут: слить с ними объявленный нестандартный заголовок нечем.
#: Перечень существует затем, чтобы отказ был у ЭТИХ единиц, а не у всех
#: объявленных: конвенция, заданная регулярным выражением, позицию имеет.
CNXML_UNITS = frozenset({"cnxml_module", "cnxml_element"})
OPENSTAX_SECTION_UNIT = "openstax_section"


def openstax_section_patterns(declaration: dict | None) -> dict:
    """One shared literal-heading convention for accounting and depth."""
    headings = (declaration or {}).get("sectionHeadings")
    if not isinstance(headings, dict) or not headings:
        raise ValueError("openstax_section requires literal sectionHeadings")
    patterns = {}
    for number, title in headings.items():
        if re.fullmatch(r"\d+\.\d+", str(number)) is None or not isinstance(title, str) or not title:
            raise ValueError("invalid OpenStax section heading")
        patterns[str(number)] = (r"^(?:" + re.escape(str(number)) + r"\n\n"
                                + re.escape(title) + r"|SOURCE-SECTION: "
                                + re.escape(str(number)) + r" " + re.escape(title)
                                + r")$")
    return patterns


def openstax_section_spans(text: str, declaration: dict | None) -> list:
    """Sections in a pinned extraction, disambiguated from numerical examples.

    A SOURCE-SECTION table marker is an excerpt, never a whole-section claim.
    Each declared publisher heading must occur exactly once in the bytes.
    """
    rows = []
    for number, pattern in openstax_section_patterns(declaration).items():
        matches = list(re.finditer(pattern, text, re.MULTILINE))
        if len(matches) != 1:
            raise ValueError(f"OpenStax section {number}: expected exactly one literal heading")
        rows.append((matches[0].start(), _Head(number, declaration["sectionHeadings"][number])))
    return sorted(rows, key=lambda row: row[0])


def cnxml_heads(text: str, unit: str) -> list:
    """Intrinsic CNXML divisions, not divisions inferred from model anchors.

    A module is a single, non-overlapping textbook division. The finer axis
    counts every CNXML element with an explicit id in content or glossary,
    including nested elements, without transferring an anchor to ancestors.
    Metadata, MathML and identifiers invented by an exporter are excluded.
    These structural denominators do not count scientific propositions.
    """
    if unit not in CNXML_UNITS:
        raise ValueError(f"unsupported CNXML division: {unit}")
    ns = "{http://cnx.rice.edu/cnxml}"
    md = "{http://cnx.rice.edu/mdml}"
    doc = ET.fromstring(text)
    if doc.tag != ns + "document":
        raise ValueError("CNXML source must be a namespaced document")
    module_nodes = doc.findall(f"{ns}metadata/{md}content-id")
    if len(module_nodes) != 1:
        raise ValueError("CNXML source needs exactly one metadata content-id")
    module = (module_nodes[0].text or "").strip()
    if not module or re.fullmatch(r"[^/#\s]+", module) is None:
        raise ValueError("CNXML source needs an unambiguous metadata content-id")
    contents = doc.findall(ns + "content")
    if len(contents) != 1:
        raise ValueError("CNXML source needs exactly one content element")
    content = contents[0]
    rows, seen = [], set()
    for section in [content, *doc.findall(ns + "glossary")]:
        for element in section.iter():
            identifier = element.get("id")
            if not element.tag.startswith(ns) or identifier is None:
                continue
            if re.fullmatch(r"[^/#\s]+", identifier) is None or identifier in seen:
                raise ValueError(f"invalid or duplicate CNXML id: {identifier!r}")
            seen.add(identifier)
            tag = element.tag[len(ns):]
            title = " ".join("".join(element.itertext()).split())[:100]
            rows.append(_Head(f"{module}#{identifier}", f"{tag}: {title}"))
    if unit == "cnxml_module":
        return [_Head(module, " ".join(doc.findtext(ns + "title", "").split()))]
    return rows


_POSITIONLESS_UNITS = frozenset({
    *CNXML_UNITS,
    "word", "ordinal", "marginal", "named_section", "ru_named_section",
    "turn", "principle",
    "policy_section",
    "kk_subsection",
    "ru_standard_clause",
    "article_roman", "en_article_roman", "fr_article",
    "fr_code_lettered_article", "verse",
    "talmud_segment",
    "tabula_item", "yar_rule", "wff_provision",
})


def article_matches(text: str, unit: str | None = None,
                    declaration: dict | None = None) -> list:
    """Заголовки единиц деления акта.

    Объявленная единица отключает автоопределение: акт знает своё деление
    лучше, чем угадывание по маркеру. Единица «слово» вдобавок параметризована
    таблицей числительных самой декларации — регулярного выражения ей мало."""
    if unit is not None:
        irregular = (declaration or {}).get("irregular_headings")
        if irregular and unit in _POSITIONLESS_UNITS:
            # Эти ветки отдают заголовки СОБРАННЫМИ, без позиции в документе, и
            # свести с ними нестандартный по месту нечем. Отказ громкий
            # намеренно: молча пропущенный заголовок отнял бы единицу у меры
            # глубины, оставив учёт статей при своих. Единицы, чья конвенция
            # задана регулярным выражением, позицию имеют и обслуживаются ниже.
            raise ValueError(
                'articles.json: "irregular_headings" вместе с объявленной '
                f'единицей unit={unit!r} эта мера не поддерживает — заголовки '
                "этой единицы возвращаются без позиции в документе")
        if unit in CNXML_UNITS:
            return cnxml_heads(text, unit)
        if unit == "word":
            return word_heads(text, declaration or {})
        if unit == "ordinal":
            return ordinal_heads(text, declaration or {})
        if unit == "marginal":
            return marginal_heads(text, declaration or {})
        if unit == "named_section":
            return named_section_heads(text, declaration or {})
        # `ru_named_section` — тот же механизм под русским языком (алиас по
        # образцу `en_point`). Здесь язык не читается вовсе, а у ПАРНОЙ
        # конвенции в verify/ci/gates/sources/check_source_pinning.py от него
        # зависят признаки исполнимого содержания, которыми проверяются
        # объявленные границы; имя обязано стоять в ОБОИХ реестрах, иначе эта
        # мера отвечает «неприменима» по документу, который измерим.
        if unit == "ru_named_section":
            return named_section_heads(text, declaration or {})
        if unit == "turn":
            return turn_heads(text, declaration or {})
        if unit == "principle":
            return principle_heads(text)
        if unit == "kk_subsection":
            return kk_subsection_heads(text)
        if unit == "ru_standard_clause":
            return ru_standard_clause_heads(text)
        if unit == "en_article_dotted":
            return en_article_dotted_heads(text)
        if unit == "en_article_upper_dotted":
            return en_article_upper_dotted_heads(text)
        if unit == "ru_article_dotted_standalone":
            return ru_article_dotted_standalone_heads(text, declaration)
        if unit in ("rfc_subsection", "spec_section"):
            return rfc_subsection_heads(text)
        if unit == "cfr_section":
            return cfr_section_heads(text)
        if unit == "rfc_2616_section":
            return rfc_2616_section_heads(text)
        if unit == "ussg_guideline":
            return ussg_guideline_heads(text, declaration)
        if unit == "policy_section":
            return policy_section_heads(text)
        if unit == "article_roman":
            return roman_article_heads(text)
        if unit == "en_article_roman":
            return en_article_roman_heads(text)
        if unit == "fr_article":
            return fr_article_heads(text)
        if unit == "fr_code_lettered_article":
            return fr_code_lettered_article_heads(text)
        if unit == "verse":
            return verse_heads(text)
        if unit == "talmud_segment":
            return talmud_segment_heads(text)
        if unit == "tabula_item":
            return tabula_item_heads(text)
        if unit == "yar_rule":
            return yar_rule_heads(text)
        if unit == "wff_provision":
            return wff_provision_heads(text)
        return [head for _, head in article_spans(text, unit, declaration)]
    return [head for _, head in article_spans(text, None, declaration)]


def es_article_word_spans(text: str, declaration: dict) -> list:
    """(позиция, заголовок) статей, чьё числительное набрано прописью.

    LOREG (Ley Orgánica 5/1985) делится 234 заголовками, и ни в одном нет
    цифры: «Artículo ciento sesenta y tres». Номер учёта при этом АРАБСКИЙ
    (locator фрагмента — `article/163`), поэтому приведение одного к другому
    делает таблица `ordinals` из `articles.json` самого акта — та же, которую
    читает `verify/ci/gates/sources/check_source_pinning.py`. Две копии
    соглашения разошлись бы, как однажды разошлись `ARTICLE_RE` и срез статьи.

    В ОТЛИЧИЕ от `word_heads`, позиция здесь СОХРАНЯЕТСЯ: заголовок стоит в
    тексте целой строкой, и леджер предложений вправе резать тела статей — то
    есть единица не попадает в `_POSITIONLESS_UNITS`, и мера объёма внутри
    статьи у испанского акта работает.
    """
    ordinals = (declaration or {}).get("ordinals") or {}
    by_phrase = {str(phrase): str(number) for number, phrase in ordinals.items()}
    if not by_phrase:
        return []
    alternatives = "|".join(re.escape(p) for p in
                            sorted(by_phrase, key=lambda p: (-len(p), p)))
    pattern = re.compile(rf"^Artículo ({alternatives})(?:\.[ \t]*(.{{0,90}})|$)",
                         re.MULTILINE)
    return [(match.start(),
             _Head(by_phrase[match.group(1)], (match.group(2) or "").strip()))
            for match in pattern.finditer(text)]


